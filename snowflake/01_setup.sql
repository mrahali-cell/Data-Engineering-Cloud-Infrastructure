-- MédiRelais · Step 1: set up the Snowflake environment (run once, by an admin)
-- BOOTSTRAP ONLY. Terraform (terraform/) now owns the warehouse, the database, the
-- BRONZE/SILVER/GOLD schemas and the MEDIRELAIS_PIPELINE role: change them there, not here.
-- This file stays as the record of how a new account is first prepared (stage, file format,
-- the first bronze tables, the pipeline grants, the GitHub integration).
-- Do not re-run it on the live account: section 5 drops the daily task and the dbt project.
-- Steps 2 and 3 then run as MEDIRELAIS_PIPELINE, never as ACCOUNTADMIN.

-- 1. Warehouse, database, schemas, file format, stage
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS MEDIRELAIS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS MEDIRELAIS;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.BRONZE;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.SILVER;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.GOLD;

CREATE FILE FORMAT IF NOT EXISTS MEDIRELAIS.BRONZE.CSV_FORMAT
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' ENCODING = 'UTF8';
CREATE STAGE IF NOT EXISTS MEDIRELAIS.BRONZE.RAW_STAGE
  FILE_FORMAT = MEDIRELAIS.BRONZE.CSV_FORMAT;

-- 2. Bronze tables: every value kept as text, exactly as received, plus where and
--    when each row came from. Types are applied in silver, so a bad value goes to
--    quarantine there instead of failing the whole load here.
CREATE TABLE IF NOT EXISTS MEDIRELAIS.BRONZE.HOSPITALS (
  hospital_id VARCHAR, hospital_name VARCHAR, city VARCHAR, beds VARCHAR,
  _source VARCHAR, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _batch_id VARCHAR);
CREATE TABLE IF NOT EXISTS MEDIRELAIS.BRONZE.PRODUCTS (
  product_id VARCHAR, product_name VARCHAR, category VARCHAR,
  unit_cost_eur VARCHAR, is_cold_chain VARCHAR, is_narcotic VARCHAR,
  _source VARCHAR, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _batch_id VARCHAR);
CREATE TABLE IF NOT EXISTS MEDIRELAIS.BRONZE.STOCK (
  snapshot_date VARCHAR, hospital_id VARCHAR, product_id VARCHAR, batch_id VARCHAR,
  qty_on_hand VARCHAR, expiry_date VARCHAR, is_recalled VARCHAR,
  _source VARCHAR, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _batch_id VARCHAR);
CREATE TABLE IF NOT EXISTS MEDIRELAIS.BRONZE.CONSUMPTION (
  consumption_date VARCHAR, hospital_id VARCHAR, product_id VARCHAR, qty_used VARCHAR,
  _source VARCHAR, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _batch_id VARCHAR);

-- 3. The pipeline role: loads bronze, builds silver and gold, runs the daily task.
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS MEDIRELAIS_PIPELINE;

USE ROLE SECURITYADMIN;
GRANT ROLE MEDIRELAIS_PIPELINE TO ROLE SYSADMIN;
-- One line per team member who runs steps 2 and 3:
-- GRANT ROLE MEDIRELAIS_PIPELINE TO USER <user_name>;

GRANT USAGE, OPERATE ON WAREHOUSE MEDIRELAIS_WH TO ROLE MEDIRELAIS_PIPELINE;
GRANT USAGE ON DATABASE MEDIRELAIS TO ROLE MEDIRELAIS_PIPELINE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE MEDIRELAIS TO ROLE MEDIRELAIS_PIPELINE;
GRANT READ, WRITE ON STAGE MEDIRELAIS.BRONZE.RAW_STAGE TO ROLE MEDIRELAIS_PIPELINE;
GRANT USAGE ON FILE FORMAT MEDIRELAIS.BRONZE.CSV_FORMAT TO ROLE MEDIRELAIS_PIPELINE;
-- bronze: append only (no UPDATE, DELETE or TRUNCATE)
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA MEDIRELAIS.BRONZE TO ROLE MEDIRELAIS_PIPELINE;
GRANT SELECT, INSERT ON FUTURE TABLES IN SCHEMA MEDIRELAIS.BRONZE TO ROLE MEDIRELAIS_PIPELINE;
-- silver and gold: dbt creates and owns these tables
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA MEDIRELAIS.SILVER TO ROLE MEDIRELAIS_PIPELINE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA MEDIRELAIS.GOLD TO ROLE MEDIRELAIS_PIPELINE;
-- PUBLIC holds the Git repository link, the dbt project and the daily task
GRANT CREATE GIT REPOSITORY, CREATE DBT PROJECT, CREATE TASK
  ON SCHEMA MEDIRELAIS.PUBLIC TO ROLE MEDIRELAIS_PIPELINE;

-- 4. Account-level pieces only ACCOUNTADMIN can create or grant
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE MEDIRELAIS_PIPELINE;

-- Lets Snowflake read our GitHub repo (it is public, so no secret is needed)
CREATE API INTEGRATION IF NOT EXISTS MEDIRELAIS_GITHUB
  API_PROVIDER = GIT_HTTPS_API
  API_ALLOWED_PREFIXES = ('https://github.com/mrahali-cell')
  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION MEDIRELAIS_GITHUB TO ROLE MEDIRELAIS_PIPELINE;

-- 5. One-time handover, only for an account set up before this role existed:
--    silver and gold tables were created as ACCOUNTADMIN, so give them to the
--    pipeline role. The old task and dbt project are dropped here and rebuilt
--    from Git by 03_schedule.sql.
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA MEDIRELAIS.SILVER TO ROLE MEDIRELAIS_PIPELINE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA MEDIRELAIS.GOLD   TO ROLE MEDIRELAIS_PIPELINE COPY CURRENT GRANTS;
DROP TASK IF EXISTS MEDIRELAIS.PUBLIC.DAILY_PIPELINE;
DROP DBT PROJECT IF EXISTS MEDIRELAIS.PUBLIC.MEDIRELAIS_DBT;
