-- MédiRelais · Step 1: set up the Snowflake environment
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS MEDIRELAIS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS MEDIRELAIS;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.BRONZE;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.SILVER;
CREATE SCHEMA IF NOT EXISTS MEDIRELAIS.GOLD;

CREATE OR REPLACE FILE FORMAT MEDIRELAIS.BRONZE.CSV_FORMAT
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' ENCODING = 'UTF8';
CREATE STAGE IF NOT EXISTS MEDIRELAIS.BRONZE.RAW_STAGE
  FILE_FORMAT = MEDIRELAIS.BRONZE.CSV_FORMAT;

CREATE OR REPLACE TABLE MEDIRELAIS.BRONZE.HOSPITALS (
  hospital_id VARCHAR, hospital_name VARCHAR, city VARCHAR, beds NUMBER);
CREATE OR REPLACE TABLE MEDIRELAIS.BRONZE.PRODUCTS (
  product_id VARCHAR, product_name VARCHAR, category VARCHAR,
  unit_cost_eur NUMBER(10,2), is_cold_chain BOOLEAN, is_narcotic BOOLEAN);
CREATE OR REPLACE TABLE MEDIRELAIS.BRONZE.STOCK (
  snapshot_date DATE, hospital_id VARCHAR, product_id VARCHAR, batch_id VARCHAR,
  qty_on_hand NUMBER, expiry_date DATE, is_recalled BOOLEAN);
CREATE OR REPLACE TABLE MEDIRELAIS.BRONZE.CONSUMPTION (
  consumption_date DATE, hospital_id VARCHAR, product_id VARCHAR, qty_used NUMBER);
